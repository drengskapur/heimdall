import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

/**
 * Generate THIRD-PARTY-NOTICES.md from the dependencies the build actually
 * ships.
 *
 * Every one of them is permissive (MIT, Apache-2.0, ISC) and every one of them
 * says the same thing: you may ship this, provided you carry the notice. The
 * bundle inlines their code into the assets a user downloads, so the notice has
 * to travel with the repository or the condition is simply unmet.
 *
 * Generated rather than hand-written because a hand-written one is accurate
 * exactly until the next `npm install`, and wrong attribution is worse than the
 * obvious absence of it. `--check` fails instead of writing, which is how
 * `test:licenses` keeps this from drifting — the same arrangement as the
 * statechart document.
 *
 * Scope is `dependencies`, not the full transitive tree: those are what Vite
 * resolves into the bundle. devDependencies build and test the thing and are
 * not distributed.
 */

const root = resolve(import.meta.dirname, "..");
const output = resolve(root, "THIRD-PARTY-NOTICES.md");

/** The license text a package ships, by convention in a file named for it. */
async function licenseText(dir) {
  const entries = await readdir(dir);
  const name = entries.find(entry => /^(LICENSE|LICENCE|COPYING)(\.\w+)?$/i.test(entry));
  if (!name) return null;
  return (await readFile(resolve(dir, name), "utf8")).trim();
}

/** A package's own NOTICE, if it has one.
 *
 *  Apache-2.0 §4(d) requires that a NOTICE file travel with derivative works,
 *  which means carrying it here rather than only the license. None of the
 *  current dependencies ships one, but that is a fact about today's install and
 *  not a property of the licenses, so it is read rather than assumed. */
async function noticeText(dir) {
  const entries = await readdir(dir);
  const name = entries.find(entry => /^NOTICE(\.\w+)?$/i.test(entry));
  if (!name) return null;
  return (await readFile(resolve(dir, name), "utf8")).trim();
}

/** A browsable URL, from whichever of npm's several shapes the package used —
 *  `repository` is frequently an SSH remote or a `git+https` clone URL, neither
 *  of which is a link a reader can follow. */
function homepageOf(own) {
  const raw = own.homepage ?? (typeof own.repository === "string" ? own.repository : own.repository?.url);
  if (!raw) return null;
  return raw
    .replace(/^git\+/, "")
    .replace(/^git@([^:]+):/, "https://$1/")
    .replace(/^git:\/\//, "https://")
    .replace(/\.git$/, "");
}

async function collect() {
  const manifest = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
  const names = Object.keys(manifest.dependencies ?? {}).sort();
  const packages = [];
  for (const name of names) {
    const dir = resolve(root, "node_modules", name);
    const own = JSON.parse(await readFile(resolve(dir, "package.json"), "utf8"));
    const text = await licenseText(dir);
    if (!text) throw new Error(`${name} ships no license file — attribution cannot be generated for it`);
    packages.push({
      name,
      version: own.version,
      license: own.license ?? "see text",
      homepage: homepageOf(own),
      text,
      notice: await noticeText(dir),
    });
  }
  return packages;
}

function render(packages) {
  const licenses = [...new Set(packages.map(p => p.license))].sort();
  return [
    "# Third-party notices",
    "",
    "Heimdall bundles the packages below into the application it serves. Each is",
    "distributed under a permissive license that permits this on the condition that",
    `its notice travels with the software; those notices are reproduced in full here.`,
    "",
    `${packages.length} packages, under ${licenses.join(", ")}.`,
    "",
    "This file is generated by `scripts/generate-third-party-notices.mjs` from the",
    "installed tree. Do not edit it by hand — run `npm run licenses:generate`.",
    "",
    "| Package | Version | License |",
    "| --- | --- | --- |",
    ...packages.map(p => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.version} | ${p.license} |`),
    "",
    ...packages.flatMap(p => [
      `## ${p.name}`,
      "",
      "```",
      p.text,
      "```",
      ...(p.notice ? ["", `NOTICE, carried per Apache-2.0 §4(d):`, "", "```", p.notice, "```"] : []),
      "",
    ]),
  ].join("\n");
}

const packages = await collect();
const rendered = `${render(packages)}\n`;

if (process.argv.includes("--check")) {
  const existing = await readFile(output, "utf8").catch(() => null);
  if (existing !== rendered) {
    console.error(
      existing === null
        ? "THIRD-PARTY-NOTICES.md is missing. Run: npm run licenses:generate"
        : "THIRD-PARTY-NOTICES.md is out of date with the installed dependencies. Run: npm run licenses:generate",
    );
    process.exitCode = 1;
  } else {
    console.log(`THIRD-PARTY-NOTICES.md is current (${packages.length} packages).`);
  }
} else {
  await writeFile(output, rendered);
  console.log(`Wrote THIRD-PARTY-NOTICES.md (${packages.length} packages).`);
}
