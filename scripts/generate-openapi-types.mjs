// Generates TypeScript interfaces from the OpenAPI sources of truth:
//   * openapi/app.openapi.json              — the app's own interfaces (authored)
//   * openapi/kubernetes/swagger-v*.json    — Kubernetes types, one per vendored
//                                             minor version (committed source)
//
// For each Kubernetes version it converts the committed swagger 2.0 to OpenAPI 3
// (a git-ignored build artifact) and emits app/lib/generated/kubernetes/v<minor>.ts,
// then writes a registry (index.ts) so adapters can select a version's types by
// the cluster's discovered server version.
//
// Run with `npm run codegen`. Refresh/extend the vendored specs with
// `npm run codegen:fetch-kube`.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const genDir = join(root, "app/lib/generated");
const kubeGenDir = join(genDir, "kubernetes");
const kubeSpecDir = join(root, "openapi/kubernetes");
mkdirSync(kubeGenDir, { recursive: true });

// Invoke CLI JS entries via `node` directly — the .cmd shim fails to spawn on
// Windows and the packages' exports maps block require.resolve of the bin.
const openapiTypescript = join(root, "node_modules/openapi-typescript/bin/cli.js");
const swagger2openapi = join(root, "node_modules/swagger2openapi/swagger2openapi.js");
const run = (bin, args) => execFileSync(process.execPath, [bin, ...args], { cwd: root, stdio: "inherit" });

// 1. App-owned interfaces.
process.stdout.write("generating app types from openapi/app.openapi.json\n");
run(openapiTypescript, ["openapi/app.openapi.json", "-o", "app/lib/generated/app-api.ts"]);

// 2. Kubernetes types, one module per vendored minor version.
const swaggers = readdirSync(kubeSpecDir)
  .map(f => /^swagger-v(\d+\.\d+)\.json$/.exec(f))
  .filter(Boolean)
  .map(m => m[1])
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
if (!swaggers.length) throw new Error("No vendored Kubernetes swaggers found (run codegen:fetch-kube).");

const ident = minor => `v${minor.replace(/\./g, "_")}`;
for (const minor of swaggers) {
  const swagger = `openapi/kubernetes/swagger-v${minor}.json`;
  const openapi = `openapi/kubernetes/openapi-v${minor}.json`; // git-ignored build artifact
  process.stdout.write(`converting + generating kubernetes ${minor}\n`);
  run(swagger2openapi, [swagger, "-o", openapi, "--patch"]);
  run(openapiTypescript, [openapi, "-o", `app/lib/generated/kubernetes/${ident(minor)}.ts`]);
}

const latest = swaggers[swaggers.length - 1];

// 3a. Lean latest alias — the app's common path imports only this, so a normal
//     typecheck loads one version's types, not all of them.
writeFileSync(
  join(kubeGenDir, "latest.ts"),
  [
    "// Generated by scripts/generate-openapi-types.mjs — do not edit.",
    `export type { components } from "./${ident(latest)}";`,
    "",
  ].join("\n"),
);

// 3b. Version registry — imported only by version-aware adapters that genuinely
//     need multiple minors at once (pulls in every version's types).
const registry = [
  "// Generated by scripts/generate-openapi-types.mjs — do not edit.",
  "// Kubernetes API types keyed by minor version, for version-aware adapters.",
  ...swaggers.map(m => `export type { components as K8s_${ident(m)} } from "./${ident(m)}";`),
  `export type { components as K8sLatest } from "./${ident(latest)}";`,
  "",
  `export const KUBERNETES_VERSIONS = ${JSON.stringify(swaggers)} as const;`,
  `export const KUBERNETES_LATEST = ${JSON.stringify(latest)} as const;`,
  "export type KubernetesMinor = (typeof KUBERNETES_VERSIONS)[number];",
  "",
].join("\n");
writeFileSync(join(kubeGenDir, "index.ts"), registry);

process.stdout.write(`openapi types generated for k8s ${swaggers.join(", ")} (latest ${latest}).\n`);
